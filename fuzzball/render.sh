#!/usr/bin/env bash
# Fill the Fuzzfile templates with this cluster's values (ask CIQ staff for them).
#
#   IMAGE=docker://<arm64 cuda pytorch + nemo automodel image> \
#   VOLUME=<persistent volume name> PROVISIONER=<storage provisioner, e.g. persistent> \
#   PORT=<allowed TCP port> NCCL_IFACE=<NIC between the two GB10s, optional> \
#   bash fuzzball/render.sh
#
# Optional: REPO_DIR (default /shared/FinscaleNvidiaPlatform), MODEL_DIR, CONFIG_1N, CONFIG_2N, GIT_URL, GIT_BRANCH
# Output: fuzzball/rendered/*.fz and fuzzball/cluster.env (sourced by node_entry.sh on every node).
#
# Values are saved to fuzzball/render.env, so later you only pass what changes, e.g.:
#   CONFIG_2N=configs/replicate-2n-r2.yaml bash fuzzball/render.sh
set -euo pipefail
cd "$(dirname "$0")"
if [[ -f render.env ]]; then  # saved values; anything set on the command line wins
  while IFS='=' read -r k v; do
    [[ -z "$k" || "$k" == \#* ]] && continue
    [[ -z "${!k:-}" ]] && export "$k=$v"
  done < render.env
fi
: "${IMAGE:?set IMAGE}" "${VOLUME:?set VOLUME}" "${PORT:?set PORT}"
PROVISIONER=${PROVISIONER:-persistent}
REPO_DIR=${REPO_DIR:-/shared/FinscaleNvidiaPlatform}
MODEL_DIR=${MODEL_DIR:-/shared/models/nemotron-3-nano-30b}
CONFIG_1N=${CONFIG_1N:-configs/single-1n.yaml}
CONFIG_2N=${CONFIG_2N:-configs/replicate-2n.yaml}
GIT_URL=${GIT_URL:-https://github.com/mkchoithani/finscale.git}
GIT_BRANCH=${GIT_BRANCH:-finscale-multinode}

mkdir -p rendered
for t in templates/*.fz; do
  sed -e "s#@IMAGE@#${IMAGE}#g" -e "s#@VOLUME@#${VOLUME}#g" -e "s#@PROVISIONER@#${PROVISIONER}#g" \
      -e "s#@REPO_DIR@#${REPO_DIR}#g" -e "s#@MODEL_DIR@#${MODEL_DIR}#g" -e "s#@PORT@#${PORT}#g" \
      -e "s#@CONFIG_1N@#${CONFIG_1N}#g" -e "s#@CONFIG_2N@#${CONFIG_2N}#g" \
      -e "s#@GIT_URL@#${GIT_URL}#g" -e "s#@GIT_BRANCH@#${GIT_BRANCH}#g" "$t" > "rendered/$(basename "$t")"
done
{
  echo "# generated by fuzzball/render.sh on $(date -u +%FT%TZ)"
  echo "export PORT=${PORT}"
  echo "export NNODES=${NNODES:-2}"
  echo "export MODEL_DIR=${MODEL_DIR}"
  [[ -n "${NCCL_IFACE:-}" ]] && echo "export NCCL_SOCKET_IFNAME=${NCCL_IFACE}"
  [[ -n "${NCCL_IB_HCA:-}" ]] && echo "export NCCL_IB_HCA=${NCCL_IB_HCA}"
  [[ -n "${NCCL_IB_DISABLE:-}" ]] && echo "export NCCL_IB_DISABLE=${NCCL_IB_DISABLE}"
  true
} > cluster.env
grep -l '@[A-Z_0-9]*@' rendered/*.fz && { echo "unfilled placeholders above" >&2; exit 1; } || true
for k in IMAGE VOLUME PROVISIONER PORT NCCL_IFACE NCCL_IB_HCA NCCL_IB_DISABLE NNODES REPO_DIR MODEL_DIR \
         CONFIG_1N CONFIG_2N GIT_URL GIT_BRANCH; do
  if [[ -n "${!k:-}" ]]; then echo "$k=${!k}"; fi
done > render.env
echo "1-node config: ${CONFIG_1N}   2-node config: ${CONFIG_2N}"
echo "Rendered: $(ls rendered/*.fz | tr '\n' ' ')"
echo "cluster.env:"; cat cluster.env
echo "Next: git add fuzzball/cluster.env fuzzball/render.env && git commit && git push; 00_setup.fz pulls them onto the volume."
